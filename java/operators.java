import java.util.*;

class operators{
    public static void main(String[] args){
        int a=5, b=3;
        System.out.println(a>>b);
        System.out.println(a<<b);
        System.out.println(a&b);
        System.out.println(a|b);
        System.out.println(~a);
        System.out.println(72564/100%10);
        System.out.println();
    }
}