import java.util.Scanner;

public class runtimearray {
    public static void main(String[] args) {
        int[] arr = new int[5];
        Scanner sc = new Scanner(System.in);
        for (int i = 0; i<=4; i++){
            arr[i] = sc.nextInt();
        }
        for (int i = 0; i<=0; i++){
            System.out.println(arr[i]);
        }
    }
    
}
